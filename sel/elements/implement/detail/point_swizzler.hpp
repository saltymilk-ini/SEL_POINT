#define POINT_SWIZZLE_MODIFY_ELEMENT(r, pre_post, element)          \
    BOOST_PP_IF                                                     \
    (                                                               \
        BOOST_PP_CAT(POINT_SWIZZLE_CONVERT_PREFIX_, element),       \
        BOOST_PP_TUPLE_ELEM(0, pre_post)                            \
        element                                                     \
        BOOST_PP_TUPLE_ELEM(1, pre_post),                           \
        sel::detail::component_position_of_ ## element              \
    )

#define POINT_SWIZZLE_CONVERT_PARAMETERS(...)                       \
    BOOST_PP_SEQ_ENUM                                               \
    (                                                               \
    	BOOST_PP_SEQ_TRANSFORM                                      \
        (                                                           \
    		POINT_SWIZZLE_MODIFY_ELEMENT,                           \
    		(sel::detail::component_position<, >()),                \
    		BOOST_PP_VARIADIC_TO_SEQ(__VA_ARGS__)                   \
    	)                                                           \
    )

